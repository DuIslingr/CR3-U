#!/usr/bin/env python3
"""engine/src/assets/nametags.inc: the message speaker tags in the game's order, read out of the
Android library (EvtWindowMessage::GetNameTagNumber's table: 144 pointers at 0x10a7178 - Ghidra's
0x11a7178 -, filled by R_AARCH64_RELATIVE relocations). A message's \\dNNN names the speaker whose
place in this table (+ 1) numbers its name in message\\name_tag.dat.

  gen_nametags.py <libcrx.so (arm64)> engine/src/assets/nametags.inc
"""
import struct
import sys

TABLE, COUNT = 0x10a7178, 0x90


def main(argv):
    if len(argv) < 3:
        print(__doc__)
        return 1
    d = open(argv[1], 'rb').read()
    if d[:4] != b'\x7fELF' or d[4] != 2:
        print('not a 64-bit ELF', file=sys.stderr)
        return 1
    shoff, = struct.unpack_from('<Q', d, 0x28)
    shentsize, shnum, shstrndx = struct.unpack_from('<HHH', d, 0x3a)
    secs = [struct.unpack_from('<IIQQQQIIQQ', d, shoff + i * shentsize) for i in range(shnum)]
    strtab = secs[shstrndx]
    name = lambda o: d[strtab[4] + o:d.index(b'\0', strtab[4] + o)].decode()
    rel = {}
    for s in secs:
        if name(s[0]) == '.rela.dyn':
            for k in range(s[5] // 24):
                off, info, add = struct.unpack_from('<QQq', d, s[4] + k * 24)
                if info & 0xffffffff == 1027:  # R_AARCH64_RELATIVE
                    rel[off] = add
    phoff, = struct.unpack_from('<Q', d, 0x20)
    phnum, = struct.unpack_from('<H', d, 0x38)
    loads = [struct.unpack_from('<IIQQQQQQ', d, phoff + i * 56) for i in range(phnum)]

    def file_offset(va):
        for p in loads:
            if p[0] == 1 and p[3] <= va < p[3] + p[5]:
                return va - p[3] + p[2]
        raise ValueError(f'{va:#x} not loaded')

    tags = []
    for i in range(COUNT):
        o = file_offset(rel[TABLE + 8 * i])
        tags.append(d[o:d.index(b'\0', o)].decode('ascii'))
    lines = ['// Generated by tools/gen_nametags.py from the Android library: EvtWindowMessage::GetNameTagNumber\'s',
             f'// table - the {COUNT} speaker tags in order (a tag\'s place + 1 numbers its name in name_tag.dat)']
    for i in range(0, COUNT, 12):
        lines.append(' '.join(f'"{t}",' for t in tags[i:i + 12]))
    open(argv[2], 'w').write('\n'.join(lines) + '\n')
    print(f'{COUNT} tags -> {argv[2]}')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
